#include <cstdio>

int main() {
    int x;
    int h, m;

    // 1. 读取输入
    scanf("%d", &x);
    scanf("%d %d", &h, &m);

    // 2. 处理分钟
    m = m + x;           // 加上经过的分钟数 x
    h = h + (m / 60);    // 如果分钟相加超过或等于 60，就给小时进位 (m/60 即为进位的小时数)
    m = m % 60;          // 进位后，保留剩余的分钟数

    // 3. 处理小时
    h = h + 6;           // 加上经过的 6 小时
    h = h % 24;          // 处理跨天情况，对 24 取模

    // 4. 按照样例格式输出
    printf("%d %d\n", h, m);

    return 0;
}